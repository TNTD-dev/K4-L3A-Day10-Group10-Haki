"""Hard benchmark tren 3 trang thai (Baseline / Corrupted / Repaired).

Chay SAU run_phase1.py va run_corruption_flow.py (can 3 Chroma collection + clean data).
    python script/run_hard_benchmark.py            # dung test set da dong bang neu co
    python script/run_hard_benchmark.py --rebuild  # sinh lai test set (LLM)
"""
from __future__ import annotations

import sys

import pandas as pd

from core.config import load_settings
from core.utils import read_json, write_text
from evaluation.hard_benchmark import build_hard_test_set, evaluate_hard
from retrieval.index import LocalEmbeddingIndex

STATES = ["baseline", "corrupted", "repaired"]


def fmt(v) -> str:
    if isinstance(v, list):
        return f"[{v[0]:.2f}, {v[1]:.2f}]"
    return f"{v:.3f}" if isinstance(v, float) else str(v)


def write_report(settings, test_payload: dict, results: dict[str, dict]) -> str:
    prov = test_payload["provenance"]
    items = test_payload["items"]
    k = settings.top_k
    rows = [
        ("Retrieval hit@1", "hit_at_1"), (f"Retrieval hit@{k}", f"hit_at_{k}"), ("MRR", "mrr"),
        ("Answer accuracy (LLM judge)", "judge_accuracy"), ("  95% CI (Wilson)", "judge_accuracy_ci95"),
        ("Mean judge score (1-5)", "mean_judge_score"), ("Wrong abstentions (answerable)", "wrong_abstentions"),
        ("**Confident wrong (answerable)**", "confident_wrong_rate"),
        ("Abstention on unanswerable", "abstention_rate"), ("**Hallucination rate (unanswerable)**", "hallucination_rate"),
        ("Judge fallbacks (phai = 0)", "judge_fallbacks"),
    ]
    table = ["| Metric | " + " | ".join(s.capitalize() for s in STATES) + " |", "|---|" + "---|" * len(STATES)]
    table += [f"| {label} | " + " | ".join(fmt(results[s].get(key)) for s in STATES) + " |" for label, key in rows]

    types = sorted({t for s in STATES for t in results[s]["by_type"]})
    by_type = ["| Type | n | " + " | ".join(f"{s.capitalize()} hit@1 / acc" for s in STATES) + " |", "|---|---|" + "---|" * len(STATES)]
    for t in types:
        n = results["baseline"]["by_type"].get(t, {}).get("n", 0)
        cells = [f"{results[s]['by_type'][t]['hit_at_1']:.2f} / {results[s]['by_type'][t]['judge_accuracy']:.2f}" if t in results[s]["by_type"] else "—" for s in STATES]
        by_type.append(f"| {t} | {n} | " + " | ".join(cells) + " |")

    examples = [f"- `{it['id']}` ({it['question_type']}): {it['question']}" for it in items[:5]]
    rejected = test_payload["rejected"]
    text = "\n\n".join([
        "# Hard Benchmark — realistic questions, generative answers, hallucination check",
        f"_Generated by `script/run_hard_benchmark.py`. Test set fingerprint `{prov['items_fingerprint']}`, "
        f"created {prov['created_at']} by `{prov['generator']}`._",
        "## Vì sao cần benchmark này",
        "Test set chính (theo Guide) đặt **nguyên title** trong câu hỏi và `qa.py` **trích nguyên** trường metadata làm câu trả lời, "
        "nên baseline chạm trần 1.0 theo thiết kế. Benchmark này đo đúng điều người dùng thật gặp.",
        "## Thiết kế & kiểm soát leakage",
        "\n".join([
            f"- {sum(i['answerable'] for i in items)} câu có đáp án (1 câu/paper, xoay vòng summary/authors/date) + "
            f"{sum(not i['answerable'] for i in items)} câu **không có đáp án** (trong domain, nghe hợp lý, đã kiểm tra không có trong corpus).",
            "- Câu hỏi **không chứa title**, mô tả paper bằng lời khác; LLM sinh **một lần** rồi đóng băng (file + fingerprint).",
            f"- Lọc tự động: loại câu có ≥{prov['leakage_filters']['title_ngram']} từ liên tiếp trùng title, "
            f"≥{prov['leakage_filters']['abstract_ngram']} từ liên tiếp trùng abstract, chứa DOI, hoặc có >{prov['leakage_filters'].get('max_unique_cues', 1)} từ khóa chỉ xuất hiện ở đúng paper đó (document frequency = 1, 'chìa khóa' lộ đáp án). Bị loại: **{len(rejected)}** lần (xem `rejected` trong test set).",
            f"- Trả lời bằng **LLM chỉ từ top-{k} context** (vector search thuần, không exact lookup), được phép trả lời \"I don't know\".",
            "- Chấm bằng LLM judge (`evaluation.metrics._judge_answer`); câu không đáp án chấm theo việc từ chối trả lời.",
        ]),
        "## Kết quả 3 trạng thái",
        "\n".join(table),
        "## Theo loại câu hỏi",
        "\n".join(by_type),
        "## Ví dụ câu hỏi",
        "\n".join(examples),
        "## Giới hạn (nêu rõ khi pitching)",
        "\n".join([
            f"- n nhỏ ({results['baseline']['answerable']} câu có đáp án) → khoảng tin cậy rộng; so sánh bằng CI, không bằng 1 con số.",
            "- Người sinh đề, người trả lời và giám khảo cùng một LLM → có thể có self-preference bias; nên chạy thêm judge khác model.",
            "- Chạy 1 lần; LLM (answer + judge) không hoàn toàn tất định: Baseline và Repaired cùng dữ liệu vẫn có thể lệch vài điểm → đọc theo CI.",
            "- Câu không đáp án do nhóm tự viết (6 câu) → đo hallucination ở mức định tính.",
        ]),
    ])
    path = settings.paths.comparison_report.parent / "hard_benchmark_report.md"
    write_text(path, text + "\n")
    return str(path)


def main() -> None:
    settings = load_settings()
    p = settings.paths
    test_path = p.eval_testset.parent / "hard_test_set.json"

    if "--rebuild" in sys.argv or not test_path.exists():
        # De sinh tu BASELINE clean data (khong bao gio tu data corrupted).
        baseline_df = pd.read_json(p.clean_json, convert_dates=False, dtype={"paper_id": str, "published": str})
        payload = build_hard_test_set(baseline_df, settings, test_path)
        print(f"[hard] built {len(payload['items'])} questions, rejected {len(payload['rejected'])} -> {test_path}")
    payload = read_json(test_path)

    manifests = {"baseline": p.embeddings_json, "corrupted": p.corrupted_embeddings_json, "repaired": p.repaired_embeddings_json}
    results = {}
    for state in STATES:
        index = LocalEmbeddingIndex.load(settings, manifests[state])
        results[state] = evaluate_hard(
            settings, index, test_path,
            p.baseline_metrics.parent / f"hard_{state}_metrics.json",
            p.baseline_metrics.parent / f"hard_{state}_answers.json",
        )
        r = results[state]
        print(f"[hard] {state:<9} hit@1={r['hit_at_1']:.2f} mrr={r['mrr']:.2f} acc={r['judge_accuracy']:.2f} "
              f"CI={r['judge_accuracy_ci95']} halluc={r['hallucination_rate']:.2f}")
    print(f"Report: {write_report(settings, payload, results)}")


if __name__ == "__main__":
    main()
